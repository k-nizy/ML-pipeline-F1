"""End-to-end check of the running API, both databases and the prediction script.

Start the services first, then run this:

    net start MySQL80
    python -m uvicorn src.api.main:app --host 127.0.0.1 --port 8000
    python scripts/smoke_test.py

It exercises every endpoint that the report claims to work, cleans up the rows
it creates, and writes the results to ``outputs/e2e_test_run.md`` so the run can
be quoted in the report instead of copied by hand. Exit code is 1 if any check
fails, so it can be used as a pre-submission gate.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import date
from pathlib import Path
from typing import Any

import requests

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = PROJECT_ROOT / "outputs" / "e2e_test_run.md"

SQL_TEST_HOUR = "2015-06-01T00:00:00"
MONGO_TEST_HOUR = "2016-01-01T00:00:00"


class Report:
    """Collects the checks so they can be printed and written as Markdown."""

    def __init__(self) -> None:
        self.rows: list[tuple[str, str, str, str]] = []
        self.passed = 0
        self.failed = 0
        self.skipped = 0

    def check(self, section: str, label: str, ok: bool, detail: str = "") -> None:
        status = "PASS" if ok else "FAIL"
        self.passed += 1 if ok else 0
        self.failed += 0 if ok else 1
        self.rows.append((section, label, status, detail))
        print(f"  {status}  {label}" + (f"  ->  {detail}" if detail else ""))

    def skip(self, section: str, label: str, detail: str) -> None:
        self.skipped += 1
        self.rows.append((section, label, "SKIP", detail))
        print(f"  SKIP  {label}  ->  {detail}")

    def as_markdown(self, base_url: str, versions: dict[str, str], prediction: dict[str, Any] | None) -> str:
        lines = [
            "# End-to-end test run",
            "",
            f"Date: {date.today().isoformat()}  ",
            f"API: `{base_url}`  ",
            f"MySQL: {versions.get('mysql', 'n/a')}  ",
            f"MongoDB: {versions.get('mongo', 'not configured')}  ",
            "Generated by `python scripts/smoke_test.py`.",
            "",
            f"**Result: {self.passed} passed, {self.failed} failed"
            + (f", {self.skipped} skipped" if self.skipped else "")
            + ".**",
            "",
            "| Section | Check | Result | Detail |",
            "|---|---|---|---|",
        ]
        for section, label, status, detail in self.rows:
            lines.append(f"| {section} | {label} | {status} | {detail or ''} |")
        if prediction:
            lines += [
                "",
                "## Prediction script output",
                "",
                "```json",
                json.dumps(prediction, indent=2),
                "```",
            ]
        lines.append("")
        return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-url", default="http://127.0.0.1:8000")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--skip-prediction", action="store_true", help="Do not run scripts/predict.py")
    args = parser.parse_args()
    base = args.base_url.rstrip("/")
    report = Report()
    versions: dict[str, str] = {}

    print("1. Service")
    try:
        health = requests.get(f"{base}/health", timeout=10)
    except requests.RequestException as exc:
        print(f"  FAIL  API is not reachable at {base}: {exc}")
        print("        Start it with: python -m uvicorn src.api.main:app --port 8000")
        return 1
    report.check("service", "GET /health", health.status_code == 200, health.json().get("status", ""))

    sql_health = requests.get(f"{base}/api/sql/health", timeout=10)
    ok = sql_health.status_code == 200
    if ok:
        versions["mysql"] = sql_health.json().get("version", "")
    report.check("service", "GET /api/sql/health", ok,
                 f"MySQL {versions.get('mysql')} db={sql_health.json().get('db')}" if ok else sql_health.text[:80])

    print("\n2. SQL time-series endpoints")
    latest = requests.get(f"{base}/api/sql/readings/latest", timeout=10)
    body = latest.json() if latest.status_code == 200 else {}
    report.check("sql", "GET latest", latest.status_code == 200 and "observed_at" in body,
                 f"{body.get('observed_at')} pm25={body.get('pm25')}")
    rng = requests.get(f"{base}/api/sql/readings/range",
                       params={"start": "2014-12-31T21:00:00", "end": "2014-12-31T23:00:00"}, timeout=10)
    rows = rng.json() if rng.status_code == 200 else []
    report.check("sql", "GET range (3 hours)", rng.status_code == 200 and len(rows) == 3,
                 f"{len(rows)} rows, x-total-count={rng.headers.get('x-total-count')}")
    stats = requests.get(f"{base}/api/sql/stats", timeout=10).json()
    report.check("sql", "GET stats", stats.get("hourly_rows") == 43824,
                 f"rows={stats.get('hourly_rows')} mean={stats.get('pm25_mean')}")

    print("\n3. SQL create, read, update, delete")
    payload = {"station_id": 1, "observed_at": SQL_TEST_HOUR, "pm25": 87.5, "dewp": 3.0,
               "temp": 22.0, "pres": 1009.0, "wind_dir": "se", "wind_speed": 2.5}
    created = requests.post(f"{base}/api/sql/readings", json=payload, timeout=10)
    reading_id = created.json().get("reading_id") if created.status_code == 201 else None
    report.check("sql", "POST create", created.status_code == 201,
                 f"id={reading_id}, wind_dir stored as {created.json().get('wind_dir') if reading_id else '?'}")
    duplicate = requests.post(f"{base}/api/sql/readings", json=payload, timeout=10)
    report.check("sql", "POST duplicate", duplicate.status_code == 409, "409 conflict on station + hour")
    single = requests.get(f"{base}/api/sql/readings/{reading_id}", timeout=10)
    report.check("sql", "GET one", single.status_code == 200 and single.json().get("pm25") == 87.5,
                 f"pm25={single.json().get('pm25')}")
    updated = requests.put(f"{base}/api/sql/readings/{reading_id}", json={"pm25": 120.0}, timeout=10)
    report.check("sql", "PUT update", updated.status_code == 200 and updated.json().get("pm25") == 120.0
                 and updated.json().get("temp") == 22.0, "only pm25 changed, temp untouched")
    repeated = requests.put(f"{base}/api/sql/readings/{reading_id}", json={"pm25": 120.0}, timeout=10)
    report.check("sql", "PUT identical again", repeated.status_code == 200,
                 "same body twice still returns 200, not a phantom 404")

    print("\n4. SQL error paths")
    report.check("sql", "GET unknown id", requests.get(f"{base}/api/sql/readings/99999999", timeout=10).status_code == 404)
    inverted = requests.get(f"{base}/api/sql/readings/range",
                            params={"start": "2014-12-31T23:00:00", "end": "2014-12-30T00:00:00"}, timeout=10)
    report.check("sql", "GET inverted range", inverted.status_code == 400, inverted.json().get("detail", "")[:60])
    bad = dict(payload, observed_at="2015-07-01T00:00:00", wind_dir="SIDEWAYS")
    report.check("sql", "POST invalid wind_dir", requests.post(f"{base}/api/sql/readings", json=bad, timeout=10).status_code == 422)

    print("\n5. SQL clean up")
    deleted = requests.delete(f"{base}/api/sql/readings/{reading_id}", timeout=10)
    report.check("sql", "DELETE", deleted.status_code == 204, f"status={deleted.status_code}")
    report.check("sql", "GET after delete", requests.get(f"{base}/api/sql/readings/{reading_id}", timeout=10).status_code == 404)
    after = requests.get(f"{base}/api/sql/stats", timeout=10).json()
    report.check("sql", "dataset unchanged", after.get("hourly_rows") == 43824, f"rows={after.get('hourly_rows')}")

    print("\n6. MongoDB")
    mongo_health = requests.get(f"{base}/api/mongo/health", timeout=15)
    if mongo_health.status_code != 200:
        reason = mongo_health.json().get("detail", mongo_health.text[:70]) if mongo_health.content else "no response"
        report.skip("mongo", "MongoDB endpoints", reason)
    else:
        versions["mongo"] = "reachable"
        report.check("mongo", "GET health", True, "connected")
        doc = {"station": {"id": 1, "name": "Beijing US Embassy", "city": "Beijing"},
               "timestamp": MONGO_TEST_HOUR,
               "target": {"pm25": 99, "imputed": False},
               "weather": {"dewp": 3.0, "temp": 22.0, "pres": 1009.0, "wind_dir": "SE",
                           "wind_speed": 2.5, "snow_hours": 0, "rain_hours": 0}}
        made = requests.post(f"{base}/api/mongo/readings", json=doc, timeout=15)
        doc_id = made.json().get("_id") if made.status_code == 201 else None
        report.check("mongo", "POST create", made.status_code == 201, f"id={doc_id}")
        again = requests.post(f"{base}/api/mongo/readings", json=doc, timeout=15)
        report.check("mongo", "POST duplicate", again.status_code == 409, "409 on station + timestamp")
        m_latest = requests.get(f"{base}/api/mongo/readings/latest", timeout=15)
        report.check("mongo", "GET latest", m_latest.status_code == 200,
                     f"timestamp={m_latest.json().get('timestamp')}")
        m_range = requests.get(f"{base}/api/mongo/readings/range",
                               params={"start": "2014-12-31T21:00:00", "end": "2014-12-31T23:00:00"}, timeout=15)
        report.check("mongo", "GET range (3 hours)", m_range.status_code == 200 and len(m_range.json()) == 3,
                     f"{len(m_range.json()) if m_range.status_code == 200 else 0} documents")
        m_put = requests.put(f"{base}/api/mongo/readings/{doc_id}", json={"target.pm25": 88}, timeout=15)
        report.check("mongo", "PUT update", m_put.status_code == 200 and m_put.json().get("target", {}).get("pm25") == 88,
                     "target.pm25 set to 88")
        m_del = requests.delete(f"{base}/api/mongo/readings/{doc_id}", timeout=15)
        report.check("mongo", "DELETE", m_del.status_code == 204, f"status={m_del.status_code}")
        report.check("mongo", "GET after delete",
                     requests.get(f"{base}/api/mongo/readings/{doc_id}", timeout=15).status_code == 404)

    print("\n7. Prediction script")
    prediction: dict[str, Any] | None = None
    if args.skip_prediction:
        report.skip("task 4", "predict.py", "skipped by flag")
    else:
        run = subprocess.run([sys.executable, str(PROJECT_ROOT / "scripts" / "predict.py")],
                             capture_output=True, text=True, cwd=PROJECT_ROOT)
        if run.returncode == 0:
            try:
                prediction = json.loads(run.stdout)
            except json.JSONDecodeError:
                prediction = None
        report.check("task 4", "predict.py exit 0", run.returncode == 0,
                     f"predicted_pm25={prediction.get('predicted_pm25'):.2f}" if prediction else run.stderr.strip()[:80])
        if prediction:
            print(json.dumps(prediction, indent=2))

    markdown = report.as_markdown(base, versions, prediction)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(markdown, encoding="utf-8")
    print(f"\nWrote {args.output.relative_to(PROJECT_ROOT)}")
    print(f"RESULT: {report.passed} passed, {report.failed} failed"
          + (f", {report.skipped} skipped" if report.skipped else ""))
    return 1 if report.failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
